package sept8;

public class AssignmentOperator {

	public static void main(String[] args) {
		int i=10;
		System.out.println("Intial value for i:"+i);//10
		i+=20;
		//i=i+20
		System.out.println("Current value for i:"+i);//30
		i-=5;
		//i=i-5
		System.out.println("Current value for i:"+i);//25
		i*=50;
		//i=i*50
		System.out.println("Current value for i:"+i);
		i/=10;
		System.out.println("Current value for i:"+i);
		
		

	}

}
